  typ=arg['type'];check={'string':f'args[{i}].isString()', 'integer':f'args[{i}].isDouble() && args[{i}].toDouble() == args[{i}].toInt()', 'number':f'args[{i}].isDouble() && std::isfinite(args[{i}].toDouble())', 'boolean':f'args[{i}].isBool()', 'array':f'args[{i}].isArray()', 'object':f'args[{i}].isObject()'}[typ]
